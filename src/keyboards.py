def list_keyboard(items: list, key: str,
                  back_label: str = "🔙 رجوع",
                  prefix: str = "") -> ReplyKeyboardMarkup:
    """Build a vertical keyboard from a list of dicts."""
    rows = [[f"{prefix}{item[key][:35]}"] for item in items]
    rows.append([back_label])
    return _kb(rows)
